def _write_new_file_private(path, text):
    """Create and write a text file with mode 0600."""
    fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)


# One-time migration from the old taxtracker config location: if nothing lives
# at the new default path yet but a key from the pre-rename app does, copy it
# forward so existing sessions/logins survive the rename instead of getting a
# freshly generated key. Only applies to the ~/.config default.
if (
    "LIFETRACKER_SECRET_KEY_FILE" not in os.environ
    and LIFETRACKER_CONFIG_DIR == _home_config_dir
    and not _key_file.exists()
):
    _old_key_file = Path.home() / ".config" / "taxtracker" / "secret_key"
    try:
        _old_stored = _old_key_file.read_text(encoding="utf-8").strip() if _old_key_file.exists() else ""
    except OSError:
        _old_stored = ""
    if _old_stored:
        try:
            _key_file.parent.mkdir(parents=True, exist_ok=True)
            _write_new_file_private(_key_file, _old_stored + "\n")
        except OSError:
            pass

try:
    _stored = _key_file.read_text(encoding="utf-8").strip() if _key_file.exists() else ""
except OSError as _e:
    raise RuntimeError(
        f"Could not read secret key file {_key_file}: {_e}. "
        "Check file permissions or set LIFETRACKER_SECRET_KEY_FILE to a readable path."
    ) from _e

if not _stored:
    _stored = secrets.token_hex(50)
    try:
        _key_file.parent.mkdir(parents=True, exist_ok=True)
        _write_new_file_private(_key_file, _stored + "\n")
    except OSError as _e:
        raise RuntimeError(
            f"Could not write secret key file {_key_file}: {_e}. "
            "Check directory permissions or set LIFETRACKER_SECRET_KEY_FILE "
            "to a writable path."
        ) from _e

SECRET_KEY = _stored

